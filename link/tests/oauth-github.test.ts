import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";
import { Hono } from "hono";

// oauth.ts's local resolveSession() wrapper calls shared/auth's `resolveSession` (imported
// there as `resolveSharedSession`) and reshapes its camelCase SharedSession into the
// snake_case { tenant_id, member_id } shape this file's routes use. Mock that real export
// name — not a `resolveSessionFromCookie` that doesn't exist on the module — so the D1
// behaviours under test never depend on cookie parsing or a live WEB_DB session lookup.
const sessionMock = vi.fn();
vi.mock("../../shared/auth", async (importActual) => ({
  ...(await importActual<Record<string, unknown>>()),
  resolveSession: (...args: unknown[]) => sessionMock(...args),
}));

import { oauthRoutes } from "../src/oauth";

// Fakes the `oauth_states` table shared/oauth-state.ts reads/writes (state was moved off
// KV onto WEB_DB — KV is only eventually consistent across edge colos, which produced false
// "Invalid or expired state" callback failures; see the 2026-08-21 tenant 100005 investigation
// and shared/oauth-state.ts's top-of-file comment). The fake mirrors the real SQL contract
// (INSERT, and DELETE ... RETURNING for one-time consumption with an expiry check) rather than
// just being a key/value stub, so these tests exercise the same prefix-matching shape the real
// D1 statements do.
// shared/oauth-state.ts binds expires_at as a SQLite datetime() modifier ("+600 seconds") so
// the stored value and datetime('now') are generated by the same function and never mismatch
// in string format (an ISO string compared against datetime('now')'s space-separated format
// is a same-day false positive — see shared/oauth-state.ts's storeOAuthState comment). This
// fake reproduces that arithmetic in JS to keep its in-memory bookkeeping correct.
function applyDatetimeModifier(modifier: string): string {
  const m = /^([+-])(\d+) seconds$/.exec(modifier);
  const deltaMs = m ? (m[1] === "-" ? -1 : 1) * Number(m[2]) * 1000 : 0;
  return new Date(Date.now() + deltaMs).toISOString();
}

function createOAuthStateDb() {
  const store = new Map<string, { data: string; expiresAt: string }>();
  const db = {
    prepare(sql: string) {
      return {
        bind(...args: unknown[]) {
          return {
            async run() {
              if (sql.startsWith("INSERT INTO oauth_states")) {
                const [state, data, modifier] = args as [string, string, string];
                store.set(state, { data, expiresAt: applyDatetimeModifier(modifier) });
              }
              return { success: true };
            },
            async first() {
              if (sql.startsWith("DELETE FROM oauth_states WHERE state")) {
                const [state] = args as [string];
                const row = store.get(state);
                store.delete(state);
                if (!row || new Date(row.expiresAt).getTime() <= Date.now()) return null;
                return { data: row.data };
              }
              return null;
            },
          };
        },
      };
    },
  } as unknown as D1Database;
  return { db, store };
}

function seedState(store: Map<string, { data: string; expiresAt: string }>, state: string, data: unknown) {
  store.set(state, { data: JSON.stringify(data), expiresAt: new Date(Date.now() + 600_000).toISOString() });
}

/**
 * `existingGitHubOwner` 是跨租户接管那道闸门的输入：GitHub 回调在 upsert 之前会按
 * (channel_type='GITHUB', source_channel_id) 查一次仍然 active 的行，读它的 tenant_id。
 * null = 这个 GitHub 账号还没人连过。
 */
function fakeDb(existingGitHubOwner: { tenant_id: number | null } | null = null) {
  const runs: Array<{ sql: string; binds: unknown[] }> = [];
  const db = {
    prepare(sql: string) {
      return {
        bind(...binds: unknown[]) {
          return {
            async run() { runs.push({ sql, binds }); return { success: true }; },
            async first() {
              if (sql.includes("SELECT tenant_id FROM channels") && sql.includes("'GITHUB'")) return existingGitHubOwner;
              return sql.includes("SELECT id FROM channels") ? { id: "chan-existing" } : null;
            },
          };
        },
      };
    },
  } as unknown as D1Database;
  return { db, runs };
}

function app(db: D1Database, webDb: D1Database) {
  const a = new Hono();
  a.route("/api/auth", oauthRoutes());
  return (path: string) => a.request(`https://link-dev.uni-scrm.com${path}`, {}, {
    LINK_DB: db, WEB_DB: webDb, GITHUB_CLIENT_ID: "cid", GITHUB_CLIENT_SECRET: "csec",
  } as never);
}

function stubGitHubOAuthFetch() {
  vi.stubGlobal("fetch", vi.fn((url: string) =>
    Promise.resolve(url.includes("login/oauth/access_token")
      ? new Response(JSON.stringify({ access_token: "gho_x", token_type: "bearer" }), { status: 200 })
      : new Response(JSON.stringify({ id: 4242, login: "zc", name: "ZC", avatar_url: "https://a/x.png" }), { status: 200 }))
  ));
}

// SharedSession shape (shared/auth.ts) is camelCase; oauth.ts's resolveSession() wrapper
// converts it to the snake_case { tenant_id, member_id } the routes below read.
beforeEach(() => { sessionMock.mockReset().mockResolvedValue({ tenantId: 7, memberId: "m1", email: "z@example.com", language: "en" }); });
afterEach(() => vi.unstubAllGlobals());

describe("GET /api/auth/github/connect", () => {
  it("未登录直接 401，不把用户送进 GitHub 授权页", async () => {
    // 这个流程只会把 channel 挂到已存在的租户上，没有「顺便注册」的分支。
    // 不在这里拦，用户会走完整个授权流程最后落在一张 401 JSON 上，什么都没连上。
    sessionMock.mockResolvedValue(null);
    const { db } = fakeDb();
    const { db: webDb } = createOAuthStateDb();
    const res = await app(db, webDb)("/api/auth/github/connect");
    expect(res.status).toBe(401);
  });

  it("登录后 302 到 GitHub，state 存进 D1", async () => {
    const { db } = fakeDb();
    const { db: webDb, store } = createOAuthStateDb();
    const res = await app(db, webDb)("/api/auth/github/connect");
    expect(res.status).toBe(302);
    const loc = new URL(res.headers.get("Location")!);
    expect(loc.host).toBe("github.com");
    expect(loc.searchParams.get("client_id")).toBe("cid");
    expect(loc.searchParams.get("redirect_uri")).toBe("https://link-dev.uni-scrm.com/api/auth/github/callback");
    const state = loc.searchParams.get("state")!;
    expect(JSON.parse(store.get(state)!.data)).toMatchObject({ tenantId: "7", provider: "github" });
  });
});

describe("GET /api/auth/github/callback", () => {
  it("换 token、取用户、写 channels 行", async () => {
    const { db: webDb, store } = createOAuthStateDb();
    seedState(store, "s1", { tenantId: "7", memberId: "m1", provider: "github" });
    vi.stubGlobal("fetch", vi.fn((url: string) =>
      Promise.resolve(url.includes("login/oauth/access_token")
        ? new Response(JSON.stringify({ access_token: "gho_x", token_type: "bearer" }), { status: 200 })
        : new Response(JSON.stringify({ id: 4242, login: "zc", name: "ZC", avatar_url: "https://a/x.png" }), { status: 200 }))
    ));

    const { db, runs } = fakeDb();
    const res = await app(db, webDb)("/api/auth/github/callback?code=c1&state=s1");

    expect(res.status).toBe(302);
    const insert = runs.find((r) => r.sql.includes("INSERT INTO channels"))!;
    expect(insert.sql).toContain("'GITHUB'");
    expect(insert.binds).toContain("4242");                 // source_channel_id
    expect(JSON.parse(insert.binds[1] as string)).toMatchObject({ login: "zc", access_token: "gho_x" });
    expect(store.has("s1")).toBe(false);                    // state 一次性
  });

  it("重连时清掉 deactivated_reason —— 健康 channel 上不该挂着上次 401 的旧原因", async () => {
    const { db: webDb, store } = createOAuthStateDb();
    seedState(store, "s1", { tenantId: "7", memberId: "m1", provider: "github" });
    stubGitHubOAuthFetch();

    const { db, runs } = fakeDb({ tenant_id: 7 });   // 同一个租户重连
    const res = await app(db, webDb)("/api/auth/github/callback?code=c1&state=s1");

    expect(res.status).toBe(302);
    const insert = runs.find((r) => r.sql.includes("INSERT INTO channels"))!;
    expect(insert.sql).toContain("deactivated_reason = NULL");
  });

  it("同一个 GitHub 账号被别的租户连着时拒绝，且一行都不写", async () => {
    // 这是 release 洪水的入口：ON CONFLICT(channel_type, source_channel_id) 会把 tenant_id
    // 改写成新租户，而 channel_poll_state 按 (channel_id, poller_name) 存、仍然
    // backfill_complete=1，dedup 用的 entity_state 却是**按 tenant_id** 存、对新租户是空的
    // —— 下一次 cron 会把最新一页上的一百条 release 全当新的发出去（真的公开发帖、真的
    // 给真人发私信），同时原租户的 flow 直接变哑。
    const { db: webDb, store } = createOAuthStateDb();
    seedState(store, "s1", { tenantId: "7", memberId: "m1", provider: "github" });
    stubGitHubOAuthFetch();

    const { db, runs } = fakeDb({ tenant_id: 99 });  // 已被租户 99 连着
    const res = await app(db, webDb)("/api/auth/github/callback?code=c1&state=s1");

    expect(res.status).toBe(409);
    const body = await res.json() as { error: string };
    expect(body.error).toContain("already connected by another workspace");
    expect(body.error).toContain("已被另一个工作区连接");   // 用户可见文案必须中英双语
    expect(runs.some((r) => r.sql.includes("INSERT INTO channels"))).toBe(false);
  });

  it("state 不存在直接 400，不换 token", async () => {
    const fetchSpy = vi.fn();
    vi.stubGlobal("fetch", fetchSpy);
    const { db } = fakeDb();
    const { db: webDb } = createOAuthStateDb();
    const res = await app(db, webDb)("/api/auth/github/callback?code=c1&state=nope");
    expect(res.status).toBe(400);
    expect(fetchSpy).not.toHaveBeenCalled();
  });
});
